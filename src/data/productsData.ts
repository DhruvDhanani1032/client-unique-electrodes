// Helper to get variants / sizes of the same family
export function getRelatedFamilyVariants(product: DetailedProduct): { id: string; label: string; url: string }[] {
  // If it's a pipe or solid rod, find other sizes in same category & material
  if (['strip-in-pipe', 'rod-in-pipe', 'solid-rod'].includes(product.category)) {
    return allProducts
      .filter((p) => p.category === product.category && p.material === product.material)
      .map((p) => {
        const label = p.diameter && p.length ? `${p.diameter}MM X ${p.length}M` : p.name;
        return {
          id: p.id,
          label,
          url: `/products/${product.category}/${product.material}/${p.id}`,
        };
      });
  }
  return [];
}

